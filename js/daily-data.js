// Day number since 1970 for a calendar day, so each list advances by one every day.
const dayNumber = ({ y, m, d }) => Math.floor(Date.UTC(y, m - 1, d) / 86400000);

export function dailyFor(day) {
  const n = dayNumber(day);
  const [ayah, surah] = AYAT[n % AYAT.length];
  const [hadith, source] = HADITH[(n + 7) % HADITH.length];
  return {
    ayah: { text: ayah, ref: surah },
    hadith: { text: hadith, ref: source },
    advice: { text: ADVICE[(n + 13) % ADVICE.length] },
  };
}
