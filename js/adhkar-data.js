function dayNight(which) {
  return DAY_NIGHT.filter((x) => !x.only || x.only === which).map(({ n, m, e, only, ...rest }) => ({
    ...rest,
    id: `${which === 'm' ? 'morning' : 'evening'}-${n}`,
    text: rest.text || (which === 'm' ? m : e),
  }));
}

