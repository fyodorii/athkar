// The surah and juz of a page (the last surah beginning on or before it).
export function pageInfo(page) {
  const p = Math.max(1, Math.min(PAGES, page));
  let s = 0;
  while (s + 1 < SURAHS.length && SURAHS[s + 1][1] <= p) s++;
  let j = 0;
  while (j + 1 < JUZ.length && JUZ[j + 1] <= p) j++;
  return { page: p, surah: s + 1, surahName: SURAHS[s][0], juz: j + 1 };
}
